"""Render tts/lines.json with Piper (en_GB-cori-high, public-domain voice) into src/03b-audio.html.

Each line gets a normal clip and a slow clip (length_scale 1.45 ~ 0.7x speed), MP3 32 kbps mono,
embedded as base64 data URIs in `const AUDIO = { key: {n, s} }`.
Usage: .venv/Scripts/python make_audio.py
"""
import base64
import json
import re
from pathlib import Path

import lameenc
from piper import PiperVoice
from piper.config import SynthesisConfig

HERE = Path(__file__).parent
MODEL = HERE / "en_GB-cori-high.onnx"
OUT = HERE.parent / "src" / "03b-audio.html"
SLOW_LENGTH_SCALE = 1.45
PAD_MS = 120
# Spoken-form overrides (display text and clip key stay unchanged). Chosen by ear.
SAY_AS = [(re.compile(r"\bgoodbye\b", re.I), lambda m: "Good bye" if m.group(0)[0].isupper() else "good bye")]


def say_as(text: str) -> str:
    for pattern, repl in SAY_AS:
        text = pattern.sub(repl, text)
    return text + "." if re.fullmatch(r"[a-z ]+", text) and " " in text else text


def render(voice: PiperVoice, text: str, length_scale: float) -> str:
    cfg = SynthesisConfig(length_scale=length_scale, noise_scale=0.6, noise_w_scale=0.7)
    pcm, rate = b"", None
    for chunk in voice.synthesize(text, syn_config=cfg):
        pcm += chunk.audio_int16_bytes
        rate = chunk.sample_rate
    if rate is None:
        raise RuntimeError(f"Piper produced no audio for {text!r}")
    pcm = b"\x00\x00" * int(rate * PAD_MS / 1000) + pcm
    enc = lameenc.Encoder()
    enc.set_bit_rate(32)
    enc.set_in_sample_rate(rate)
    enc.set_channels(1)
    enc.set_quality(2)
    mp3 = enc.encode(pcm) + enc.flush()
    return "data:audio/mpeg;base64," + base64.b64encode(mp3).decode("ascii")


def main() -> None:
    lines = json.loads((HERE / "lines.json").read_text(encoding="utf-8"))
    voice = PiperVoice.load(str(MODEL))
    clips = {}
    for item in lines:
        if item["key"] in clips:
            continue
        spoken = say_as(item["text"])
        clips[item["key"]] = {"n": render(voice, spoken, 1.0), "s": render(voice, spoken, SLOW_LENGTH_SCALE)}
        print("ok:", spoken)
    body = ",\n".join(f'{json.dumps(k)}:{{"n":"{v["n"]}","s":"{v["s"]}"}}' for k, v in sorted(clips.items()))
    OUT.write_text(
        "<script>\n/* AUDIO – generated by tts/make_audio.py (Piper, voice en_GB-cori-high, public domain).\n"
        "   Do not edit by hand. Add content, rebuild, run tts/export-lines.js + make_audio.py, rebuild.\n"
        "   Lines without a clip fall back to the device voice. */\n"
        f"const AUDIO = {{\n{body}\n}};\n</script>\n",
        encoding="utf-8",
    )
    print(f"{len(clips)} clips -> {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
